-- ------------------------------------------------------------------------------
-- TRANSACTIONAL RPC FOR CONFIRMATION & SAFE INVENTORY UPDATE
-- ------------------------------------------------------------------------------
create or replace function public.confirm_prescription_and_update_stock(
  p_prescription_id text,
  p_medicine_name text,
  p_actor_name text,
  p_actor_role text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item record;
  v_deducted boolean := false;
begin
  -- 1. Update prescription status
  update public.prescriptions
  set status = 'confirmed', updated_at = timezone('utc', now())
  where id = p_prescription_id;

  -- 2. Try to match medicine in inventory and safely deduct 1 pack
  select * into v_item
  from public.inventory_items
  where lower(medicine) = lower(p_medicine_name)
  limit 1;

  if found and v_item.stock > 0 then
    update public.inventory_items
    set stock = stock - 1, updated_at = timezone('utc', now())
    where id = v_item.id;
    v_deducted := true;
  end if;

  -- 3. Log audit event
  insert into public.audit_events (id, actor_name, actor_role, action, entity, entity_id, details)
  values (
    'AE-' || substr(gen_random_uuid()::text, 1, 8),
    p_actor_name,
    p_actor_role,
    'Prescription confirmed' || (case when v_deducted then ' & inventory stock deducted' else '' end),
    'Prescription',
    p_prescription_id,
    'Confirmed prescription ' || p_prescription_id || ' for ' || p_medicine_name
  );

  return jsonb_build_object(
    'success', true,
    'prescription_id', p_prescription_id,
    'stock_deducted', v_deducted
  );
end;
$$;

