-- ------------------------------------------------------------------------------
-- 5. PRESCRIPTION FIELDS (Extracted Structured Data)
-- ------------------------------------------------------------------------------
create table if not exists public.prescription_fields (
  id bigint generated by default as identity primary key,
  prescription_id text not null references public.prescriptions(id) on delete cascade,
  label text not null,
  value text not null,
  confidence integer not null check (confidence >= 0 and confidence <= 100),
  needs_verification boolean not null default false
);

-- ------------------------------------------------------------------------------
-- 6. REFILL REQUESTS (Patient Requests & Pharmacy Approvals)
